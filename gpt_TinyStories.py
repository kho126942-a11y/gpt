"""## 1. Multi-head attention


"""

class Head(nn.Module):  # 하나의 Attention Head를 의미
    def __init__(self, emb_dim, head_size, block_size, dropout=0.1):
        super().__init__()
        self.key = nn.Linear(emb_dim, head_size, bias=False) # emb_dim을 head_size로 바꾼다
        self.query = nn.Linear(emb_dim, head_size, bias=False)
        self.value = nn.Linear(emb_dim, head_size, bias=False)
        self.register_buffer("tril", torch.tril(torch.ones(block_size, block_size))) #모든 원소가 1인 행렬 생성하여 하삼각행렬로 만든다.
                                                                                     # register_buffer를 사용한 이유는 모델을 GPU로 옮길 때 tril도 같이 옮기기 위해
        self.dropout = nn.Dropout(dropout)

    def forward(self, x):
        B, T, C = x.shape # if x.shape=(64,64,384), B=64, T=64, C=384, 64개의 문장, 64개의 토큰, 384차원 임베딩
        k = self.key(x) # (64,64,384)->(64,64,64)
        q = self.query(x)
        v = self.value(x)
        wei = q @ k.transpose(-2, -1) * (k.size(-1) ** -0.5) # k.transpose(-2, -1)은 두 자리 바꾸기로 @있는 행렬은 현재 단어가 다른 단어를 얼마나 참고할지를 의미(attention score).
                                                             # 곱하기 뒤에는 큰 차원에서는 내적값이 너무 커지기에(scaling)
        wei = wei.masked_fill(self.tril[:T, :T] == 0, float("-inf")) # Masking: 행렬에서 위 삼각형을 0으로 만들고 -inf로 만든다. 미래 정보를 제거하기 위해 사용
        wei = F.softmax(wei, dim=-1) # 총 합이 1이되도록 확률을 계산해준다. -inf인 위치는 0 확률이 된다.
        wei = self.dropout(wei) # 과적합 방지를 위해 일부 attention weight를 랜덤하게 제거
        out = wei @ v # attention 가중치 x value
        return out

class MultiHeadAttention(nn.Module):
    def __init__(self, emb_dim, num_heads, block_size, dropout=0.1):
        super().__init__()
        head_size = emb_dim // num_heads
        self.heads = nn.ModuleList([Head(emb_dim, head_size, block_size, dropout) for _ in range(num_heads)]) # head 여러개 생성
        self.proj = nn.Linear(emb_dim, emb_dim)
        self.dropout = nn.Dropout(dropout)

    def forward(self, x):
        out = torch.cat([h(x) for h in self.heads], dim=-1) # torch.cat은 차원을 연결. 즉 더하기를 해준다. dim=-1이므로 마지막 차원 덧셈
        out = self.proj(out) # 각 head의 정보를 섞어주기 위해
        out = self.dropout(out)
        return out

"""## 2. Feedforward + Block"""

class FeedForward(nn.Module): # MLP
    def __init__(self, emb_dim, dropout=0.1):
        super().__init__()
        self.net = nn.Sequential(
            nn.Linear(emb_dim, 4 * emb_dim), # 차원을 4배 늘린다.
            nn.ReLU(),   # 음수를 0으로 만든다
            nn.Linear(4 * emb_dim, emb_dim), # 4배가 된 차원을 원래 차원으로 축소한다.
            nn.Dropout(dropout),
        )
    def forward(self, x):
        return self.net(x)

class Block(nn.Module): # transformer의 한 layer를 의미
    def __init__(self, emb_dim, num_heads, block_size, dropout=0.1):
        super().__init__()
        self.ln1 = nn.LayerNorm(emb_dim) # 각 토큰의 feature를 정규화. 비슷한 스케일로 맞춤.
        self.sa = MultiHeadAttention(emb_dim, num_heads, block_size, dropout)
        self.ln2 = nn.LayerNorm(emb_dim)
        self.ffwd = FeedForward(emb_dim, dropout)

    def forward(self, x):
        x = x + self.sa(self.ln1(x)) # residual connection : 원래 정보+ 새로운 정보. Attention은 토큰 끼리 정보를 주고 받는다.
        x = x + self.ffwd(self.ln2(x)) # feedforward는 각 토큰의 표현력 강화
        return x

"""## 3. Tiny GPT"""

class TinyGPT(nn.Module):
    def __init__(self, vocab_size, block_size, emb_dim=128, num_heads=4, num_layers=4, dropout=0.1):
        super().__init__()
        self.token_embedding = nn.Embedding(vocab_size, emb_dim) # 65개의 문자를 128차원 벡터로 바꾸는 것
        self.position_embedding = nn.Embedding(block_size, emb_dim) # 순서 정보가 없기에 64개 각각의 위치에 대한 벡터 학습
        self.blocks = nn.Sequential(*[
            Block(emb_dim, num_heads, block_size, dropout) for _ in range(num_layers)
        ])
        self.ln_f = nn.LayerNorm(emb_dim)
        self.lm_head = nn.Linear(emb_dim, vocab_size) # 각 문자에 대한 점수를 만들기 위해

    def forward(self, x):
        B, T = x.shape
        pos = torch.arange(T, device=x.device) # tensor([0,1,2,....,63])
        tok = self.token_embedding(x)
        pos = self.position_embedding(pos)[None] # 차원을 맞춰주기 위해 (64,128) -> (1,64,128)
        h = tok + pos # Broadcasting 때문에 (64,64,128)
        h = self.blocks(h)
        h = self.ln_f(h)
        logits = self.lm_head(h) # (64,64,65)
        return logits

