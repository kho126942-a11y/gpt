"""## 4. 학습"""

def sequence_cross_entropy(logits, targets):
    return F.cross_entropy(logits.transpose(1, 2), targets) # F.cross_entropy는 class 차원이 두 번째에 있어야 하기에 바꿔주고 이를 targets과 비교한다. 각 위치마다 65개의 문자 중 정답 문자를 맞히는 loss 계산

def train_one_epoch(model, loader, optimizer, device, max_steps=None):
    model.train()
    total_loss, total_count = 0.0, 0
    for step, (xb, yb) in enumerate(loader):
        xb, yb = xb.to(device), yb.to(device)
        logits = model(xb)
        loss = sequence_cross_entropy(logits, yb) # 모델 예측값 logits와 정답 yb를 비교. loss가 작을수록 모델이 다음 문자를 잘 맞히는 것. 처음에는 보통 loss가 크고, 학습할수록 작아진다.
        optimizer.zero_grad()
        loss.backward() # gradient 계산
        optimizer.step() # 계산된 gradient를 이용해 모델의 가중치 업데이트
        total_loss += loss.item() * xb.size(0) # batch별 평균 loss 곱하기 batch size
        total_count += xb.size(0)
        if max_steps is not None and step + 1 >= max_steps: # 한 반복마다 최대 max_steps번의 업데이트만 함
            break
    return total_loss / total_count # 한 epoch 동안의 평균 loss

device = "cuda" if torch.cuda.is_available() else "cpu"
model = TinyGPT(vocab_size, block_size).to(device)
optimizer = torch.optim.AdamW(model.parameters(), lr=3e-4)

for epoch in range(50):
    train_loss = train_one_epoch(model, loader, optimizer, device, max_steps=300)
    print(f"epoch {epoch:2d} | train loss {train_loss:.4f}")

"""## 5. Sampling"""

@torch.no_grad() # 생성할 때는 예측만 하면 되기에 gradient 계산은 끈다.
def sample_gpt(model, block_size, stoi, itos, device, start_text="Once upon a time", max_new_tokens=400):
    model.eval()
    context = torch.zeros((1, block_size), dtype=torch.long, device=device)
    for ch in start_text:
        if ch in stoi:
            ix = torch.tensor([[stoi[ch]]], device=device)
            context = torch.cat([context[:, 1:], ix], dim=1)
    out = list(start_text)
    for _ in range(max_new_tokens):
        logits = model(context)
        logits = logits[:, -1, :]
        probs = F.softmax(logits, dim=-1)
        ix = torch.multinomial(probs, num_samples=1)
        out.append(itos[ix.item()])
        context = torch.cat([context[:, 1:], ix], dim=1)
    return "".join(out)

print(sample_gpt(model, block_size, stoi, itos, device, start_text="Once upon a time", max_new_tokens=500))

